-- Quick check question bank: single-choice questions tied to lessons. correct_index is 0-based; the Postgres arrays are 1-based.
CREATE TABLE check_question (
    id              VARCHAR(64) PRIMARY KEY CHECK (id ~ '^[a-z0-9-]+$'),
    lesson_id       BIGINT      NOT NULL REFERENCES lesson (id) ON DELETE CASCADE,
    area            VARCHAR(16) NOT NULL CHECK (area IN ('saving', 'debt', 'investing', 'risk', 'retirement')),
    level           VARCHAR(8)  NOT NULL CHECK (level IN ('easy', 'hard')),
    account_prompt  TEXT,
    slots           TEXT[]      NOT NULL CHECK (slots <@ ARRAY['savingsBalance', 'savingsInterestRate', 'monthOut', 'loanRemaining',
                                                          'loanApr', 'cardUsed', 'cardLimit', 'etfMonthly', 'depotTotal', 'positionCount']),
    generic_prompt  TEXT        NOT NULL,
    options         TEXT[]      NOT NULL CHECK (cardinality(options) BETWEEN 3 AND 4),
    correct_index   INT         NOT NULL,
    misconceptions  TEXT[]      NOT NULL,
    checks          TEXT        NOT NULL,
    CHECK (cardinality(misconceptions) = cardinality(options)),
    CHECK (correct_index BETWEEN 0 AND cardinality(options) - 1),
    CHECK (misconceptions[correct_index + 1] IS NULL),
    CHECK (cardinality(array_positions(misconceptions, NULL)) = 1)
);

