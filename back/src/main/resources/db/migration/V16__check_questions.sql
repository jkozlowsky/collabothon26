-- Quick check pool: open questions tied to lessons. `criterion` is the judge's rubric and never leaves the backend.
CREATE TABLE check_question (
    id              VARCHAR(64) PRIMARY KEY CHECK (id ~ '^[a-z0-9-]+$'),
    category        VARCHAR(16) NOT NULL,
    area            VARCHAR(16) NOT NULL,
    lesson_id       BIGINT REFERENCES lesson (id) ON DELETE SET NULL,
    account_prompt  TEXT,
    slots           TEXT[] NOT NULL,
    generic_prompt  TEXT NOT NULL,
    criterion       TEXT NOT NULL,
    CHECK ((category = 'finance' AND area IN ('saving', 'debt'))
        OR (category = 'investing' AND area IN ('investing', 'risk', 'retirement')))
);

